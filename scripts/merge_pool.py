"""Merge literature-pool shards (lit_pool/<agent>.md) into the generated index lit_pool.md.

merge_pool.py <campaign dir>

Entry IDs look like P-<agent>-<n>. When the same ID appears in several shards, fields from shards other than
its origin shard override the origin (so a verifier's status: verified wins over the sweeper's rough).
Reports: counts, rough entries still unverified, possible duplicates (same source), and entries whose notes
name an obstruction (candidates for barriers.md).
"""
import re
import sys
from collections import Counter

import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))  # works under python -I too
from rclib import Campaign, read_cards, utf8_stdout

ORDER = {"target": 0, "tool": 1, "background": 2}


def origin(pid: str) -> str:
    m = re.match(r"P-([A-Za-z0-9]+)-", pid)
    return m.group(1) if m else ""


def main():
    utf8_stdout()
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    c = Campaign(sys.argv[1])
    entries: dict = {}
    for f in sorted(c.p("lit_pool").glob("*.md")):
        if f.name == "README.md":
            continue
        shard = re.sub(r"^inherited_.*?_", "", f.stem)
        for card in read_cards(f):
            pid = card["_id"]
            cur = entries.setdefault(pid, {"_id": pid, "_title": card["_title"], "_shards": []})
            cur["_shards"].append(shard)
            fields = {k: v for k, v in card.items() if not k.startswith("_") and v}
            if shard == origin(pid) or len(cur["_shards"]) == 1:
                for k, v in fields.items():
                    cur.setdefault(k, v)
                if card["_title"]:
                    cur["_title"] = card["_title"]
            else:
                cur.update(fields)
    if not entries:
        print("pool is empty")
        return

    def key(e):
        return (ORDER.get(e.get("relevance", "background"), 3), e.get("status", "rough") != "verified", e["_id"])

    ordered = sorted(entries.values(), key=key)
    st = Counter(e.get("status", "rough") for e in ordered)
    rel = Counter(e.get("relevance", "?") for e in ordered)
    by_src: dict = {}
    for e in ordered:
        s = re.sub(r"[#?].*$", "", e.get("source", "").strip().lower().rstrip("/"))
        if s:
            by_src.setdefault(s, []).append(e["_id"])
    dups = {s: ids for s, ids in by_src.items() if len(ids) > 1}
    obstr = [e["_id"] for e in ordered if e.get("obstructions", "").strip() not in ("", "-", "none")]

    out = ["# Literature pool (GENERATED by merge_pool.py — edit the shards in lit_pool/, not this file)", "",
           f"Entries: {len(ordered)} | status {dict(st)} | relevance {dict(rel)}", "",
           "## Index", "", "| ID | status | relevance | read | title | source |", "|---|---|---|---|---|---|"]
    for e in ordered:
        out.append(f"| {e['_id']} | {e.get('status', 'rough')} | {e.get('relevance', '?')} | {e.get('read', 'no')} "
                   f"| {e['_title'][:70]} | {e.get('source', '')[:60]} |")
    out.append("")
    for e in ordered:
        out.append(f"## {e['_id']} {e['_title']}")
        for k, v in e.items():
            if k.startswith("_"):
                continue
            lines = str(v).splitlines() or [""]
            out.append(f"- {k}: {lines[0]}")
            out += ["  " + x for x in lines[1:]]
        out.append(f"- shards: {', '.join(e['_shards'])}")
        out.append("")
    c.p("lit_pool.md").write_text("\n".join(out), encoding="utf-8")

    print(f"merged {len(ordered)} entries -> {c.p('lit_pool.md')}")
    print(f"status: {dict(st)}   relevance: {dict(rel)}")
    rough = [e["_id"] for e in ordered if e.get("status", "rough") == "rough"]
    if rough:
        print(f"still rough (unverified): {len(rough)} -> {', '.join(rough[:30])}{' …' if len(rough) > 30 else ''}")
    for s, ids in dups.items():
        print(f"possible duplicate source {s}: {', '.join(ids)}")
    if obstr:
        print(f"entries naming obstructions (register in barriers.md if relevant): {', '.join(obstr)}")
    to_read = [e["_id"] for e in ordered if e.get("status") == "verified"
               and e.get("relevance") in ("target", "tool") and e.get("read", "no") == "no"]
    if to_read:
        print(f"verified + relevant but not yet read: {', '.join(to_read)}")


if __name__ == "__main__":
    main()
